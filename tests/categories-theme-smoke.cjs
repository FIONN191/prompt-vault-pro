const { _electron: electron } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const root = path.resolve(__dirname, '..')
const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'prompt-vault-settings-'))
const executable = process.env.PROMPT_VAULT_TEST_EXECUTABLE
const launch = () => electron.launch({ executablePath: executable || require('electron'), args: [...(executable ? [] : [root]), '--user-data-dir=' + profile], env: { ...process.env, VITE_DEV_SERVER_URL: '' } })
async function ready(desktop) {
  await desktop.firstWindow()
  for (let i = 0; i < 100 && (desktop.windows().length !== 3 || desktop.windows().some(win => !win.url().startsWith('file:'))); i++) await new Promise(r => setTimeout(r, 100))
  return { main: desktop.windows().find(win => !win.url().includes('desktop-')), panel: desktop.windows().find(win => win.url().includes('desktop-panel')), orb: desktop.windows().find(win => win.url().includes('desktop-orb')) }
}
;(async () => {
  let desktop = await launch()
  const errors = []
  try {
    let { main, panel, orb } = await ready(desktop)
    for (const win of desktop.windows()) win.on('pageerror', e => errors.push(e.message))
    await main.getByLabel('界面主题').waitFor()
    assert.equal(await orb.locator('button').evaluate(node => getComputedStyle(node).cursor), 'grab')
    for (const win of [main, panel, orb]) await win.waitForFunction(() => document.documentElement.dataset.theme === 'minimal')
    const original = await main.evaluate(() => JSON.parse(localStorage.getItem('prompt_vault_pro_prompts_v1')))
    await main.getByRole('button', { name: '提示词库', exact: true }).first().click()
    await main.screenshot({ path: path.join(profile, 'minimal-library.png') })
    await main.getByRole('button', { name: '管理分类', exact: true }).click()
    let dialog = main.getByRole('dialog', { name: '管理分类' })
    await dialog.getByLabel('分类名称', { exact: true }).fill('图片与后期')
    await dialog.getByLabel('分类说明', { exact: true }).fill('图片修改与视觉处理')
    await dialog.getByRole('button', { name: '+ 新增分类', exact: true }).click()
    await dialog.getByLabel('分类名称', { exact: true }).fill('品牌文案')
    await dialog.getByRole('button', { name: '上移分类', exact: true }).click()
    await dialog.getByLabel('分类栏标题').fill('我的工作分类')
    await dialog.getByLabel('全部入口名称').fill('全部素材')
    await dialog.getByLabel('收藏入口名称').fill('常用收藏')
    await dialog.getByRole('button', { name: '保存设置', exact: true }).click()
    await main.getByText('分类与侧栏设置已保存', { exact: true }).waitFor()
    let settings = await main.evaluate(() => JSON.parse(localStorage.getItem('prompt_vault_pro_preferences_v1')))
    assert.equal(settings.categories[0].zh, '图片与后期')
    assert.equal(settings.categories.at(-2).zh, '品牌文案')
    const customId = settings.categories.find(c => c.zh === '品牌文案').id
    assert.deepEqual(await main.evaluate(() => JSON.parse(localStorage.getItem('prompt_vault_pro_prompts_v1'))), original)
    await orb.getByRole('button', { name: '打开快速提示词', exact: true }).click()
    await panel.getByLabel('快速录入分类').selectOption(customId)
    await panel.getByPlaceholder('标题（可留空，自动生成）').fill('自定义分类实测')
    await panel.locator('textarea').fill('为品牌设计一句简洁文案')
    await panel.getByRole('button', { name: '存入素材库', exact: true }).click()
    await panel.getByText('已存入素材库', { exact: true }).waitFor()
    await panel.keyboard.press('Escape')
    await main.getByRole('button', { name: '管理分类', exact: true }).click()
    dialog = main.getByRole('dialog', { name: '管理分类' })
    await dialog.getByRole('button', { name: /品牌文案/ }).click()
    await dialog.getByLabel('分类名称', { exact: true }).fill('品牌写作')
    await dialog.getByRole('button', { name: '保存设置', exact: true }).click()
    await main.waitForFunction(id => JSON.parse(localStorage.getItem('prompt_vault_pro_preferences_v1')).categories.some(c => c.id === id && c.zh === '品牌写作'), customId)
    assert.equal((await main.evaluate(() => JSON.parse(localStorage.getItem('prompt_vault_pro_prompts_v1')))).find(p => p.title === '自定义分类实测').category, customId)
    // Full editor sees the same custom category; do not save this temporary draft.
    await main.getByRole('button', { name: '+ 新建', exact: true }).click()
    await main.getByLabel('分类', { exact: true }).selectOption(customId)
    await main.getByRole('button', { name: '取消', exact: true }).click()
    for (const theme of ['light', 'neon', 'minimal']) {
      await main.getByLabel('界面主题').selectOption(theme)
      for (const win of [main, panel, orb]) await win.waitForFunction(value => document.documentElement.dataset.theme === value, theme)
      if (theme !== 'minimal') await main.screenshot({ path: path.join(profile, theme + '-library.png') })
    }
    await main.getByRole('button', { name: '管理分类', exact: true }).click()
    dialog = main.getByRole('dialog', { name: '管理分类' })
    await dialog.getByRole('button', { name: /品牌写作/ }).click()
    await dialog.screenshot({ path: path.join(profile, 'category-manager.png') })
    await dialog.getByRole('button', { name: '移除这个分类…', exact: true }).click()
    await dialog.getByLabel('迁移到分类').selectOption('Image Editing')
    await dialog.getByRole('button', { name: '确认移除分类', exact: true }).click()
    await dialog.getByRole('button', { name: '保存设置', exact: true }).click()
    await main.waitForFunction(id => !JSON.parse(localStorage.getItem('prompt_vault_pro_preferences_v1')).categories.some(c => c.id === id), customId)
    const after = await main.evaluate(() => JSON.parse(localStorage.getItem('prompt_vault_pro_prompts_v1')))
    assert.equal(after.length, original.length + 1)
    assert.equal(after.find(p => p.title === '自定义分类实测').category, 'Image Editing')
    await panel.waitForFunction(() => document.querySelector('select[aria-label="快速录入分类"]').value === 'Image Editing')
    // Import through the UI, opting into appearance restoration.
    await main.getByRole('button', { name: '导入/导出', exact: true }).first().click()
    await main.getByLabel('同时恢复备份中的分类属性、主题和分类栏名称').check()
    const backup = { version: 2, prompts: [{ id: 'import-check', title: '导入验证', category: 'import-category', chinesePrompt: '备份内容' }], preferences: { theme: 'light', categories: [{ id: 'import-category', zh: '导入分类', color: '#445566', description: '备份说明' }], sidebar: { title: '恢复的分类栏', allLabel: '所有内容', favoritesLabel: '收藏夹', showCounts: false } } }
    await main.locator('input[type=file]').setInputFiles({ name: 'test-backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup)) })
    await main.getByText('导入成功：新增 1 条', { exact: true }).waitFor()
    for (const win of [main, panel, orb]) await win.waitForFunction(() => document.documentElement.dataset.theme === 'light')
    settings = await main.evaluate(() => JSON.parse(localStorage.getItem('prompt_vault_pro_preferences_v1')))
    assert.equal(settings.categories[0].id, 'import-category')
    assert.equal(settings.sidebar.showCounts, false)
    for (const view of ['生成器', '锻造工坊']) {
      await main.getByRole('button', { name: view, exact: true }).first().click()
      assert.equal(await main.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false)
    }
    await desktop.close()
    desktop = await launch()
    ;({ main, panel, orb } = await ready(desktop))
    await main.getByLabel('界面主题').waitFor()
    assert.equal(await main.getByLabel('界面主题').inputValue(), 'light')
    await main.getByText('恢复的分类栏', { exact: true }).waitFor()
    assert.equal((await main.evaluate(() => JSON.parse(localStorage.getItem('prompt_vault_pro_prompts_v1')))).length, original.length + 2)
    assert.deepEqual(errors, [])
    console.log(JSON.stringify({ passed: true, profile, count: original.length + 2, checks: ['default minimal', 'rename legacy category', 'add and reorder', 'custom sidebar', 'quick add and full editor', 'cross-window themes', 'safe migration on category removal', 'backup settings restoration', 'restart persistence'] }, null, 2))
  } finally { await desktop.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
