const { _electron } = require('playwright')
const fs = require('node:fs'), path = require('node:path'), os = require('node:os'), assert = require('node:assert/strict')
const root = path.resolve(__dirname, '..'), profile = fs.mkdtempSync(path.join(os.tmpdir(), 'pvp-voyager-'))
const infile = path.join(profile, 'voyager.json')
fs.writeFileSync(infile, JSON.stringify({format:'gemini-voyager.prompts.v1',items:[{id:'smoke',text:'原始 Voyager 导入测试',tags:['Voyager测试'],createdAt:1700000000000}]}))
;(async()=>{
 const executable = process.env.PROMPT_VAULT_TEST_EXECUTABLE
 const app = await _electron.launch({executablePath:executable || require('electron'),args:[...(executable?[]:[root]),'--user-data-dir='+profile],env:{...process.env,VITE_DEV_SERVER_URL:''}})
 try {
  await app.firstWindow()
  for(let i=0;i<100&&(app.windows().length<3||app.windows().some(w=>!w.url().startsWith('file:')));i++)await new Promise(r=>setTimeout(r,100))
  const main=app.windows().find(w=>!w.url().includes('desktop-')),panel=app.windows().find(w=>w.url().includes('desktop-panel'))
  await main.getByLabel('界面主题').waitFor()
  const count=()=>main.evaluate(()=>JSON.parse(localStorage.getItem('prompt_vault_pro_prompts_v1')).length)
  const before=await count()
  await main.evaluate(()=>window.desktopPrompt.toggle())
  await panel.getByRole('button',{name:'⚙ 提示词数据',exact:true}).click()
  await app.evaluate(({dialog},file)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[file]})},infile)
  await panel.getByRole('button',{name:'↑ 导入',exact:true}).click()
  await panel.getByText('合并完成：新增 1 条，更新 0 条',{exact:true}).waitFor()
  assert.equal(await count(),before+1)
  await panel.getByRole('button',{name:'↑ 导入',exact:true}).click()
  await panel.getByText('合并完成：新增 0 条，更新 0 条',{exact:true}).waitFor()
  assert.equal(await count(),before+1)
  await panel.getByLabel('搜索提示词或标签').fill('Voyager测试')
  await panel.getByRole('button',{name:'复制 原始 Voyager 导入测试',exact:true}).waitFor()
  await main.getByRole('button',{name:'导入/导出',exact:true}).click()
  await main.locator('input[type=file]').setInputFiles(infile)
  await main.getByText('导入成功：新增 0 条，更新 0 条',{exact:true}).waitFor()
  assert.equal(await count(),before+1)
  await panel.screenshot({path:path.join(profile,'import-verified.png')})
  console.log(JSON.stringify({passed:true,profile,checks:['native file picker import','shared main storage','repeat without duplicates','search imported tag','main import shares deduplication']}))
 } finally { await app.close() }
})().catch(e=>{console.error(e);process.exitCode=1})
