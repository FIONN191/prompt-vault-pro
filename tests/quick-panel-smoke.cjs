// macOS smoke check using an isolated profile and real native mouse events.
const { _electron } = require('playwright');
const fs = require('fs'), os = require('os'), path = require('path'), assert = require('assert/strict');
const {execFileSync} = require('child_process');
const root=path.resolve(__dirname, '..'), profile=fs.mkdtempSync(path.join(os.tmpdir(),'pvp-panel-check-'));
const driver=path.join(profile,'mouse');
execFileSync('swiftc',[path.join(root,'tests/native-orb-drag.swift'),'-o',driver]);
(async()=>{
 const executable=process.env.PROMPT_VAULT_TEST_EXECUTABLE;
 const app=await _electron.launch({executablePath:executable || require(path.join(root,'node_modules/electron')),args:[...(executable ? [] : [root]),'--user-data-dir='+profile],env:{...process.env,VITE_DEV_SERVER_URL:''}});
 let cursor, clipboardBefore;
 try{
 await app.firstWindow();
 for(let i=0;i<100 && (app.windows().length!==3 || app.windows().some(p=>!p.url().startsWith('file:')));i++)await new Promise(r=>setTimeout(r,100));
 const main=app.windows().find(p=>!p.url().includes('desktop-'));
 const panel=app.windows().find(p=>p.url().includes('desktop-panel'));
 await main.getByLabel('界面主题').waitFor();
 await main.evaluate(()=>window.desktopPrompt.toggle());
 const title=panel.getByPlaceholder('标题（可留空，自动生成）');
 await panel.getByLabel('搜索提示词或标签').waitFor();
 await panel.locator("aside").evaluate(async n=>{await Promise.all(n.getAnimations().map(a=>a.finished))});
 const bounds=()=>app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(w=>w.webContents.getURL().includes('desktop-panel')).getBounds());
 clipboardBefore=await app.evaluate(({clipboard})=>clipboard.readText());
 await app.evaluate(({BrowserWindow})=>{const p=BrowserWindow.getAllWindows().find(w=>w.webContents.getURL().includes("desktop-panel"));p.show();p.focus()});
 await new Promise(r=>setTimeout(r,500));
 cursor=await app.evaluate(({screen})=>screen.getCursorScreenPoint());
 const before=await bounds();
 const from={x:before.x+75,y:before.y+26};
 const to={x:from.x-170,y:from.y+50};
 execFileSync(driver,['drag',from.x,from.y,to.x,to.y].map(String));
 await new Promise(r=>setTimeout(r,250));
 const after=await bounds();

 console.log({before,after});
 assert(before.x-after.x>50,'panel must follow native horizontal drag');
 assert(after.y-before.y>20,'panel must follow native vertical drag');
 await panel.screenshot({path:path.join(profile,'quick-panel-dark.png')});
 const count=await panel.locator('.qv-card').count();
 assert(count>0);
 await panel.getByLabel('搜索提示词或标签').fill('no-match-xyz123');
 await panel.getByText('没有匹配的提示词',{exact:true}).waitFor();
 await panel.getByRole('button',{name:'清空筛选',exact:true}).click();
 assert.equal(await panel.locator('.qv-card').count(),count);
 const firstTag=panel.locator('.qv-tags button').nth(1);
 const tag=await firstTag.innerText();
 await firstTag.click();
 assert(await panel.locator('.qv-card').count()>0);
 const tagged=await panel.locator('.qv-card-copy').first().getAttribute('aria-label');
 await panel.locator('.qv-card-copy').first().click();
 await panel.getByText('已复制，切回目标应用粘贴即可',{exact:true}).waitFor();
 assert((await app.evaluate(({clipboard})=>clipboard.readText())).length>0);
 await panel.getByRole('button',{name:'全部',exact:true}).click();
 await panel.locator('.qv-favorites').click();
 assert.equal(await panel.locator('.qv-card').count(),Number(await panel.locator('.qv-favorites small').innerText()));
 await panel.locator('.qv-favorites').click();
 await panel.getByLabel('切换网格视图').click();
 assert(await panel.locator('.qv-results.is-grid').count());
 await panel.getByLabel('切换列表视图').click();
 await panel.getByLabel('切换到浅色模式').click();
 await panel.waitForFunction(()=>document.documentElement.dataset.theme==='light');
 await main.waitForFunction(()=>document.documentElement.dataset.theme==='light');
 await panel.screenshot({path:path.join(profile,'quick-panel-light.png')});
 await panel.getByLabel('切换到深色模式').click();
 await panel.waitForFunction(()=>document.documentElement.dataset.theme==='minimal');
 // The position lock disables only the header's native drag region.
 await panel.getByLabel('固定面板位置').click();
 const lockedBounds=await bounds();
 const lockFrom={x:lockedBounds.x+75,y:lockedBounds.y+26};
 execFileSync(driver,['drag',lockFrom.x,lockFrom.y,lockFrom.x-100,lockFrom.y+25].map(String));
 assert.deepEqual(await bounds(),lockedBounds);
 await panel.getByLabel('解锁面板位置').click();
 await panel.getByRole('button',{name:'+ 新增',exact:true}).click();
 await title.fill('快速面板测试条目');
 await panel.locator('textarea').fill('这是一条独立测试提示词。');
 await panel.getByRole('button',{name:'存入素材库',exact:true}).click();
 await panel.getByText('已存入素材库',{exact:true}).waitFor();
 assert.equal(await panel.locator('textarea').inputValue(),'');
 await title.fill('拖动后的草稿');
 assert.equal(await title.inputValue(),'拖动后的草稿');
 assert.deepEqual(await bounds(),after,'input must not move panel');
 // Real native click proves the close button is excluded from the drag region.
 const box=await panel.getByRole('button',{name:'关闭',exact:true}).boundingBox();
 const close={x:after.x+box.x+box.width/2,y:after.y+box.y+box.height/2};
 execFileSync(driver,['drag',close.x,close.y,close.x,close.y].map(String));
 await new Promise(r=>setTimeout(r,200));
 assert.equal(await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows().find(w=>w.webContents.getURL().includes('desktop-panel')).isVisible()),false);
 await main.evaluate(()=>window.desktopPrompt.toggle());
 await title.waitFor();
 assert.equal(await title.inputValue(),'拖动后的草稿');
 console.log(JSON.stringify({passed:true,before,after,checks:['native header drag','input usable','native close click','draft retained','search and empty state','tag filter','copy clipboard','favorites','grid view','theme sync','position lock','quick save'],profile}));
 }finally{if(clipboardBefore!==undefined)await app.evaluate(({clipboard},text)=>clipboard.writeText(text),clipboardBefore);if(cursor)execFileSync(driver,['move',cursor.x,cursor.y].map(String));await app.close();}
})().catch(e=>{console.error(e);process.exitCode=1});
