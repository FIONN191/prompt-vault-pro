const { _electron } = require('playwright')
const fs=require('node:fs'),os=require('node:os'),path=require('node:path'),assert=require('node:assert/strict')
const root=path.resolve(__dirname,'..'),profile=fs.mkdtempSync(path.join(os.tmpdir(),'pvp-edit-'))
const launch=()=>_electron.launch({executablePath:require('electron'),args:[root,'--user-data-dir='+profile],env:{...process.env,VITE_DEV_SERVER_URL:''}})
async function pages(app){
 await app.firstWindow()
 for(let i=0;i<100&&(app.windows().length!==3||app.windows().some(p=>!p.url().startsWith('file:')));i++)await new Promise(r=>setTimeout(r,100))
 const main=app.windows().find(p=>!p.url().includes('desktop-')),panel=app.windows().find(p=>p.url().includes('desktop-panel'))
 await main.getByLabel('界面主题').waitFor();await main.evaluate(()=>window.desktopPrompt.toggle());await panel.locator('.qv-card').first().waitFor()
 return {main,panel}
}
const read=main=>main.evaluate(()=>JSON.parse(localStorage.getItem('prompt_vault_pro_prompts_v1')))
;(async()=>{
 let app
 try{
 app=await launch();let {main,panel}=await pages(app)
 const clipboard=await app.evaluate(({clipboard})=>clipboard.readText())
 const before=await read(main),title=await panel.locator('.qv-card-title').first().innerText()
 const old=before.find(p=>title.includes(p.title));assert(old)
 await panel.locator('.qv-card').first().click({button:'right'})
 let dialog=panel.getByRole('dialog',{name:'编辑提示词'});await dialog.waitFor()
 assert.equal(await dialog.getByLabel('标题 *',{exact:true}).inputValue(),old.title)
 await dialog.getByLabel('标题 *',{exact:true}).fill('Discarded edit')
 await dialog.press('Escape');await dialog.waitFor({state:'detached'})
 assert.deepEqual(await read(main),before)
 await panel.locator('.qv-card').first().click({button:'right'})
 await dialog.getByLabel('标题 *',{exact:true}).fill('Edited fixture')
 await dialog.locator('textarea').nth(0).fill('测试 {subject}')
 await dialog.getByLabel('标签（逗号分隔）').fill('edit-test, fixture')
 await dialog.getByRole('button',{name:'保存修改'}).click()
 await dialog.waitFor({state:'detached'})
 await panel.locator('.qv-card-title').filter({hasText:'Edited fixture'}).waitFor()
 let after=await read(main),edited=after.find(p=>p.id===old.id)
 assert.equal(after.length,before.length)
 assert.equal(edited.title,'Edited fixture');assert.equal(edited.chinesePrompt,'测试 {subject}')
 assert.deepEqual(edited.tags,['edit-test','fixture'])
 for(const key of ['createdAt','lastUsedAt','useCount','isFavorite','englishPrompt'])assert.deepEqual(edited[key],old[key],key)
 assert.equal(await app.evaluate(({clipboard})=>clipboard.readText()),clipboard)
 // Server rejects unknown IDs instead of creating a duplicate.
 const missing=await panel.evaluate(()=>new Promise(resolve=>{
  const off=window.desktopPrompt.onResult(r=>{if(r.requestId==='missing-edit'){off();resolve(r)}})
  window.desktopPrompt.command({type:'edit',requestId:'missing-edit',id:'missing',form:{title:'No'}})
 }))
 assert.equal(missing.ok,false)
 await panel.getByLabel('切换网格视图').click()
 await panel.locator('.qv-card-title').filter({hasText:'Edited fixture'}).click({button:'right'})
 await dialog.getByLabel('标题 *',{exact:true}).fill('')
 await dialog.getByRole('button',{name:'保存修改'}).click()
 await dialog.getByText('标题不能为空',{exact:true}).waitFor()
 await dialog.getByRole('button',{name:'取消',exact:true}).click()
 await app.close();app=await launch();({main,panel}=await pages(app))
 assert.equal((await read(main)).find(p=>p.id===old.id).title,'Edited fixture')
 console.log(JSON.stringify({passed:true,checks:['right click list/grid','cancel and Escape','save original ID','preserve metadata','no clipboard side effect','validation','reject deleted prompt','restart persistence'],profile}))
 }finally{await app?.close()}
})().catch(e=>{console.error(e);process.exitCode=1})
