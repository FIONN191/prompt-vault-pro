const { _electron: electron } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const root = path.resolve(__dirname, '..')
const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'prompt-vault-sidebar-'))
const executable = process.env.PROMPT_VAULT_TEST_EXECUTABLE
const launch = () => electron.launch({ executablePath: executable || require('electron'), args: [...(executable ? [] : [root]), '--user-data-dir=' + profile], env: { ...process.env, VITE_DEV_SERVER_URL: '' } })
async function mainWindow(app) {
  await app.firstWindow()
  for (let i = 0; i < 100 && (app.windows().length !== 3 || app.windows().some(win => !win.url().startsWith('file:'))); i++) await new Promise(resolve => setTimeout(resolve, 100))
  const win = app.windows().find(page => !page.url().includes('desktop-'))
  await win.getByLabel('界面主题').waitFor()
  return win
}
;(async () => {
  let app = await launch()
  const errors = []
  try {
    let main = await mainWindow(app)
    main.on('pageerror', error => errors.push(error.message))
    const rail = main.locator('aside:visible')
    const add = rail.getByRole('button', { name: '+ 新增分类', exact: true })
    const input = rail.getByLabel('新分类名称')
    const categories = () => main.evaluate(() => JSON.parse(localStorage.getItem('prompt_vault_pro_preferences_v1')).categories)
    await main.getByRole('button', { name: '提示词库', exact: true }).first().click()
    await add.click()
    assert.equal(await input.evaluate(node => node === document.activeElement), true)
    await input.fill('  ')
    await input.press('Enter')
    await rail.getByRole('alert').filter({ hasText: '请输入分类名称' }).waitFor()
    await input.fill(' 图片编辑 ')
    await input.press('Enter')
    await rail.getByRole('alert').filter({ hasText: '已有同名分类' }).waitFor()
    await input.fill('品牌写作')
    // Candidate confirmation in a Chinese IME must not submit the form.
    await input.dispatchEvent('compositionstart')
    await input.press('Enter')
    assert.equal(await input.isVisible(), true)
    await input.dispatchEvent('compositionend')
    await main.screenshot({ path: path.join(profile, 'sidebar-add-category.png') })
    // A failed localStorage write must preserve the draft and not mutate state.
    await main.evaluate(() => {
      window.originalStorageSetItem = Storage.prototype.setItem
      Storage.prototype.setItem = function(key, value) {
        if (key === 'prompt_vault_pro_preferences_v1') throw new DOMException('Quota exceeded', 'QuotaExceededError')
        return window.originalStorageSetItem.call(this, key, value)
      }
    })
    await input.press('Enter')
    await rail.getByRole('alert').filter({ hasText: '分类保存失败' }).waitFor()
    assert.equal(await input.inputValue(), '品牌写作')
    await main.evaluate(() => { Storage.prototype.setItem = window.originalStorageSetItem; delete window.originalStorageSetItem })
    await input.press('Enter')
    await main.getByText('已创建分类「品牌写作」', { exact: true }).waitFor()
    const created = (await categories()).find(c => c.zh === '品牌写作')
    assert.ok(created)
    assert.equal(await input.count(), 0)
    assert.ok((await rail.getByRole('button', { name: /品牌写作/ }).getAttribute('class')).includes('bg-panel-3'))
    await add.click()
    await input.fill('取消的分类')
    await input.press('Escape')
    assert.equal((await categories()).some(c => c.zh === '取消的分类'), false)
    await main.waitForFunction(() => document.activeElement?.textContent?.trim() === '+ 新增分类')
    assert.equal(await add.evaluate(node => node === document.activeElement), true)
    await main.getByRole('button', { name: '+ 新建', exact: true }).click()
    await main.getByLabel('分类', { exact: true }).selectOption(created.id)
    await main.getByRole('button', { name: '取消', exact: true }).click()
    // Narrow windows have a separate drawer form and must focus its visible input.
    await main.setViewportSize({ width: 800, height: 850 })
    await main.getByRole('button', { name: '打开分类栏' }).click()
    await add.click()
    assert.equal(await input.evaluate(node => node === document.activeElement), true)
    await input.fill('移动侧栏分类')
    await rail.getByRole('button', { name: '创建', exact: true }).click()
    await main.getByText('已创建分类「移动侧栏分类」', { exact: true }).waitFor()
    assert.equal(await main.locator('aside:visible').count(), 0)
    await app.close()
    app = await launch()
    main = await mainWindow(app)
    await main.getByRole('button', { name: /品牌写作/ }).waitFor()
    await main.getByRole('button', { name: /移动侧栏分类/ }).waitFor()
    assert.deepEqual(errors, [])
    console.log(JSON.stringify({ passed: true, profile, checks: ['inline creation', 'empty and duplicate validation', 'Chinese IME', 'storage failure recovery', 'automatic selection', 'Escape cancellation', 'editor category', 'mobile drawer focus and creation', 'restart persistence'] }, null, 2))
  } finally { await app.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
