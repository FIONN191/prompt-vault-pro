const { _electron, chromium } = require('playwright')
const fs = require('node:fs'), os = require('node:os'), path = require('node:path'), assert = require('node:assert/strict')
const root = path.resolve(__dirname, '..'), profile = fs.mkdtempSync(path.join(os.tmpdir(), 'pvp-settings-'))
;(async () => {
  const executable = process.env.PROMPT_VAULT_TEST_EXECUTABLE
  const app = await _electron.launch({ executablePath: executable || require('electron'), args: [...(executable ? [] : [root]), '--user-data-dir=' + profile], env: { ...process.env, VITE_DEV_SERVER_URL: '' } })
  let browser
  try {
    await app.firstWindow()
    for (let i = 0; i < 100 && (app.windows().length < 3 || app.windows().some(p => !p.url().startsWith('file:'))); i++) await new Promise(r => setTimeout(r, 100))
    const main = app.windows().find(p => !p.url().includes('desktop-')), panel = app.windows().find(p => p.url().includes('desktop-panel'))
    const count = await main.evaluate(() => JSON.parse(localStorage.getItem('prompt_vault_pro_prompts_v1')).length)
    await main.getByRole('button', { name: '账号与设置', exact: true }).first().click()
    await main.getByRole('heading', { name: '账号与设置', exact: true }).waitFor()
    assert.equal(await main.getByRole('checkbox', { name: /开机自启/ }).isDisabled(), true)
    assert.equal(await main.getByRole('button', { name: /Apple 登录.*未启用/ }).isDisabled(), true)
    await main.getByRole('button', { name: 'Firebase 项目配置', exact: true }).click()
    for (const [key, value] of Object.entries({ apiKey: 'bad', projectId: 'test', appId: 'bad' })) await main.getByLabel(key, { exact: true }).fill(value)
    await main.getByRole('button', { name: '保存项目配置', exact: true }).click()
    await main.getByRole('alert').filter({ hasText: '有效的 Firebase' }).waitFor()
    for (const [key, value] of Object.entries({ apiKey: 'AIza' + 'x'.repeat(35), projectId: 'prompt-vault-test', appId: '1:123:web:123', authDomain: '' })) await main.getByLabel(key, { exact: true }).fill(value)
    await main.getByRole('button', { name: '保存项目配置', exact: true }).click()
    await main.getByRole('status').filter({ hasText: '项目配置已保存' }).waitFor()
    await app.evaluate(({ shell }) => { global.testLoginURL = null; shell.openExternal = async url => { global.testLoginURL = url } })
    await main.getByRole('button', { name: 'Google 登录', exact: true }).click()
    await main.getByText('等待系统浏览器完成登录…', { exact: true }).waitFor()
    const url = await app.evaluate(() => global.testLoginURL)
    assert(url.startsWith('http://127.0.0.1:'))
    browser = await chromium.launch({ headless: true, channel: 'chrome' })
    const authPage = await browser.newPage()
    await authPage.goto(url)
    await authPage.getByRole('heading', { name: '使用 Google 登录' }).waitFor()
    assert(await authPage.getByRole('button', { name: '继续使用 Google' }).isEnabled())
    await authPage.screenshot({ path: path.join(profile, 'browser-auth.png') })
    await main.getByRole('button', { name: '取消登录', exact: true }).click()
    await main.getByRole('button', { name: 'Google 登录', exact: true }).waitFor()
    assert.equal((await panel.evaluate(() => window.desktopPrompt.account('status'))).ok, false)
    assert.equal((await panel.evaluate(() => window.desktopPrompt.settings('startup', true))).ok, false)
    await main.getByRole('button', { name: /浅色.*柔和白底/ }).click()
    await panel.waitForFunction(() => document.documentElement.dataset.theme === 'light')
    await main.getByRole('button', { name: /简洁.*深色灰阶/ }).click()
    await main.evaluate(() => window.scrollTo(0, 0))
    await main.screenshot({ path: path.join(profile, 'settings.png'), fullPage: true })
    await main.getByRole('button', { name: '打开快速面板', exact: true }).click()
    await panel.getByRole('button', { name: '设置', exact: true }).click()
    await main.getByRole('heading', { name: '账号与设置', exact: true }).waitFor()
    assert.equal(await main.evaluate(() => JSON.parse(localStorage.getItem('prompt_vault_pro_prompts_v1')).length), count)
    console.log(JSON.stringify({ passed: true, profile, checks: ['settings UI and config validation', 'isolated startup cannot change OS', 'system-browser page serves Firebase SDK', 'cancel login', 'untrusted panel account IPC blocked', 'theme sync', 'panel settings entry', 'prompt data preserved'] }))
  } finally { await browser?.close(); await app.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
